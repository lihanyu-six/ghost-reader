# ---------------------------------------------------------------- 正版渠道
# 本软件只提供「书目元数据 + 正版平台检索入口」：
# 不内置书籍正文，不代下载，也不引导任何盗版来源。
# 下面三个链接都是平台官方的公开检索页，跳转后由用户自行决定是否购买/订阅。
QIDIAN_SO = "https://www.qidian.com/so/{}.html"
WEREAD_SO = "https://weread.qq.com/web/search/books?keyword={}"
BAIDU_SO = "https://www.baidu.com/s?wd={}"


def search_url(title: str) -> str:
    """起点中文网检索页（正版）。"""
    from urllib.parse import quote
    return QIDIAN_SO.format(quote(title))


def weread_url(title: str) -> str:
    """微信读书检索页（正版）。"""
    from urllib.parse import quote
    return WEREAD_SO.format(quote(title))


def info_url(title: str) -> str:
    """看简介与读者评价。"""
    from urllib.parse import quote
    return BAIDU_SO.format(quote(title + " 小说 简介 评价"))
